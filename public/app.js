function readItemDrafts() {
  if (state.view !== "items") return;
  state.items = state.items.map((item) => {
    const root = document.querySelector(`[data-item-edit="${item.id}"]`);
    if (!root) return item;
    const value = (field) => {
      const el = root.querySelector(`[data-field="${field}"]`);
      return el ? el.value : "";
    };
    const typeEl = root.querySelector('[data-field="type"]');
    const type = typeEl ? (typeEl.value === "interval" ? "interval" : "qty") : item.type;
    const next = {
      ...item,
      type,
      nameAr: value("nameAr"),
      nameEn: value("nameEn"),
      noteAr: value("noteAr"),
    };
    if (type === "interval") next.intervalHours = Number(value("intervalHours")) || item.intervalHours || 72;
    else next.required = value("required") === "" ? 0 : Number(value("required"));
    return next;
  });
}

