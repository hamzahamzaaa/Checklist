async function saveCheck() {
  if (!formComplete() || state.saving) return;
  const missing = liveShortages();
  if (!confirm(missing.length ? t("confirmSend") : t("confirmSave"))) return;
  state.saving = true;
  refreshSummary();
  const counts = {};
  for (const item of state.items) {
    if (item.type === "qty") counts[item.id] = Number(state.counts[item.id]);
  }
  try {
    const data = await api("/api/checks", {
      method: "POST",
      timeout: 30000,
      body: {
        date: state.date,
        paramedicName: state.paramedic.trim(),
        notes: state.notes.trim(),
        counts,
        cleaniseptLastChange: state.cleanisept ? new Date(state.cleanisept).toISOString() : "",
      },
    });
    state.saving = false;
    state.dirty = false;
    state.editing = false;
    state.savedCheck = data.check;
    state.selectedId = data.check.id;
    state.myChecks = (state.myChecks || []).filter((check) => check.id !== data.check.id);
    state.myChecks.unshift(data.check);
    const email = data.check.email || {};
    const map = {
      sent: t("emailSent"),
      nothing_missing: t("savedComplete"),
      not_configured: t("savedNoEmailDone"),
      failed: t("savedEmailFailed"),
    };
    const ok = email.reason === "sent" || email.reason === "nothing_missing";
    showToast(map[email.reason] || t("saved"), ok ? "" : "bad");
    return openRecords();
  } catch (err) {
    state.saving = false;
    refreshSummary();
    const timedOut = err.name === "TimeoutError" || err.name === "AbortError";
    showToast(timedOut ? te("timeout") : te(err.code), "bad");
  }
}

function onInput(event) {
  const target = event.target;
  if (target.dataset && target.dataset.field === "type") {
    if (event.type !== "change") return;
    readItemDrafts();
    render();
    return;
  }
  if (target.dataset && target.dataset.count) {
    state.counts[target.dataset.count] = target.value;
    state.dirty = true;
    state.result = null;
    refreshRow(target.dataset.count);
    refreshSummary();
  }
  if (target.id === "cleanisept") {
    state.cleanisept = target.value;
    state.dirty = true;
    state.result = null;
    const interval = state.items.find((item) => item.type === "interval");
    if (interval) refreshRow(interval.id);
    refreshSummary();
  }
  if (target.id === "paramedic") {
    state.paramedic = target.value;
    state.dirty = true;
    state.result = null;
    refreshSummary();
  }
  if (target.id === "notes") {
    state.notes = target.value;
    state.dirty = true;
    state.result = null;
  }
  if (target.id === "check-date" && event.type === "change" && target.value && target.value !== state.date) {
    if (state.dirty && !confirm(t("discard"))) {
      target.value = state.date;
      return;
    }
    openChecklist(target.value);
  }
}

