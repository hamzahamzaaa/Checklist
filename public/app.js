async function onClick(event) {
  const button = event.target.closest("[data-action]");
  if (!button) return;
  const action = button.dataset.action;
  if (action === "lang") {
    state.lang = button.dataset.lang;
    localStorage.setItem("lang", state.lang);
    render();
    return;
  }
  if (action === "logout") {
    await api("/api/logout", { method: "POST", body: {} });
    state.me = null;
    state.dirty = false;
    render();
    return;
  }
  if (action === "nav") return go(button.dataset.view);
  if (action === "edit-check") {
    if (!state.savedCheck) return;
    applyCheck(state.savedCheck);
    render();
    return;
  }
  if (action === "step") {
    const id = button.dataset.id;
    const dir = Number(button.dataset.dir);
    const current = state.counts[id] === "" || state.counts[id] == null ? 0 : Number(state.counts[id]);
    const next = Math.max(0, (Number.isFinite(current) ? current : 0) + dir);
    state.counts[id] = String(next);
    state.dirty = true;
    state.result = null;
    const input = document.querySelector(`[data-count="${id}"]`);
    if (input) input.value = String(next);
    refreshRow(id);
    refreshSummary();
    return;
  }
  if (action === "cleanisept-now") {
    state.cleanisept = nowLocalValue();
    state.dirty = true;
    state.result = null;
    const input = document.getElementById("cleanisept");
    if (input) input.value = state.cleanisept;
    const interval = state.items.find((item) => item.type === "interval");
    if (interval) refreshRow(interval.id);
    refreshSummary();
    return;
  }
  if (action === "filter") {
    state.filter = button.dataset.filter;
    render();
    return;
  }
  if (action === "select-check") {
    state.selectedId = state.selectedId === button.dataset.id ? null : button.dataset.id;
    render();
    return;
  }
  if (action === "save-items") return saveItems();
  if (action === "add-supply") return addSupply();
  if (action === "remove-supply") {
    readItemDrafts();
    if (state.items.length < 2) {
      showToast(t("keepOne"), "bad");
      return;
    }
    if (!confirm(t("removeSupplyConfirm"))) return;
    state.items = state.items.filter((item) => item.id !== button.dataset.id);
    render();
    return;
  }
  if (action === "test-email") {
    try {
      await api("/api/settings/test-email", { method: "POST", body: {} });
      showToast(t("testOk"));
    } catch (err) {
      const extra = err.payload && err.payload.message ? ` — ${err.payload.message}` : "";
      showToast(te(err.code) + extra, "bad");
    }
    return;
  }
  if (action === "delete-check") {
    const id = button.dataset.id || state.selectedId;
    const check = (state.checks || []).find((row) => row.id === id);
    if (!id || !confirm(t("deleteLogConfirm"))) return;
    const query = check && check.date && check.userId
      ? `?date=${encodeURIComponent(check.date)}&userId=${encodeURIComponent(check.userId)}`
      : "";
    let removed = false;
    try {
      await api(`/api/checks/${encodeURIComponent(id)}${query}`, { method: "DELETE" });
      removed = true;
    } catch (err) {
      if (err.code !== "not_found") {
        showToast(te(err.code), "bad");
        return;
      }
    }
    state.selectedId = null;
    await openRecords();
    const stillThere = (state.checks || []).some((row) => row.id === id || (check && row.date === check.date && row.userId === check.userId));
    if (removed || !stillThere) showToast(t("logDeleted"));
    else showToast(te("not_found"), "bad");
    return;
  }
  if (action === "resend") {
    try {
      const data = await api(`/api/checks/${button.dataset.id}/resend`, { method: "POST", body: {} });
      state.checks = state.checks.map((check) => (check.id === data.check.id ? data.check : check));
      showToast(data.check.email && data.check.email.sent ? t("emailSent") : te(data.check.email.reason || "email_failed"), data.check.email && data.check.email.sent ? "" : "bad");
      render();
    } catch (err) {
      showToast(te(err.code), "bad");
    }
    return;
  }
  if (action === "reset-password") {
    const input = document.querySelector(`[data-reset="${button.dataset.id}"]`);
    try {
      await api(`/api/users/${button.dataset.id}/password`, { method: "POST", body: { password: input.value } });
      input.value = "";
      showToast(t("pwChanged"));
    } catch (err) {
      showToast(te(err.code), "bad");
    }
    return;
  }
  if (action === "delete-user") {
    try {
      await api(`/api/users/${button.dataset.id}`, { method: "DELETE" });
      state.users = state.users.filter((user) => user.id !== button.dataset.id);
      showToast(t("userDeleted"));
      render();
    } catch (err) {
      showToast(te(err.code), "bad");
    }
  }
}

app.addEventListener("click", onClick);
