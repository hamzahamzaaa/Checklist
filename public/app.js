app.addEventListener("submit", onSubmit);

async function boot() {
  try {
    const data = await api("/api/me");
    state.me = data.user;
    if (!state.me) render();
    else await enterApp();
  } catch (err) {
    state.me = null;
    state.loginError = te(err.code || "server");
    render();
  }
}

