function t(key) {
  return (STR[state.lang] && STR[state.lang][key]) || key;
}

function te(code) {
  return (ERR[state.lang] && ERR[state.lang][code]) || code;
}

function esc(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function todayISO() {
  const d = new Date();
  const z = (n) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${z(d.getMonth() + 1)}-${z(d.getDate())}`;
}

function nowLocalValue() {
  const d = new Date();
  const z = (n) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${z(d.getMonth() + 1)}-${z(d.getDate())}T${z(d.getHours())}:${z(d.getMinutes())}`;
}

function monthLabel(iso) {
  const [y, m] = iso.split("-").map(Number);
  return `${MONTHS[state.lang][m - 1]} ${y}`;
}

function itemTitle(item) {
  return state.lang === "ar" ? item.nameAr : item.nameEn;
}

function itemSub(item) {
  const other = state.lang === "ar" ? item.nameEn : item.nameAr;
  return [other, item.noteAr].filter(Boolean).join(" · ");
}

function showToast(message, kind) {
  let el = document.getElementById("toast");
  if (!el) {
    el = document.createElement("div");
    el.id = "toast";
    document.body.appendChild(el);
  }
  el.className = `toast ${kind || ""}`;
  el.textContent = message;
  clearTimeout(showToast._t);
  showToast._t = setTimeout(() => el.remove(), 4200);
}

async function api(url, options = {}) {
  const res = await fetch(url, {
    method: options.method || "GET",
    headers: { "Content-Type": "application/json" },
    credentials: "same-origin",
    body: options.body ? JSON.stringify(options.body) : undefined,
    signal: options.timeout ? AbortSignal.timeout(options.timeout) : undefined,
  });
  const data = await res.json().catch(() => ({}));
  if (res.status === 401 && url !== "/api/login") {
    state.me = null;
    state.view = "login";
    render();
  }
  if (!res.ok) {
    const error = new Error(data.error || "server");
    error.code = data.error || "server";
    error.payload = data;
    throw error;
  }
  return data;
}

function rowState(item) {
  if (item.type === "interval") {
    const hours = item.intervalHours || 72;
    if (!state.cleanisept) return { kind: "overdue", label: t("notRecorded") };
    const diff = (Date.now() - new Date(state.cleanisept).getTime()) / 36e5;
    if (Number.isNaN(diff) || diff > hours) return { kind: "overdue", label: t("overdue") };
    return { kind: "ok", label: t("within") };
  }
  const raw = state.counts[item.id];
  if (raw === "" || raw == null) return { kind: "pending", label: "—" };
  const actual = Number(raw);
  if (!Number.isInteger(actual) || actual < 0) return { kind: "pending", label: "—" };
  if (actual < item.required) return { kind: "short", label: `${t("short")} ${item.required - actual}` };
  if (actual > item.required) return { kind: "over", label: t("surplus") };
  return { kind: "ok", label: t("complete") };
}

function liveShortages() {
  const out = [];
  for (const item of state.items) {
    const status = rowState(item);
    if (item.type === "qty") {
      if (status.kind !== "short") continue;
      out.push({ item, kind: "qty", missing: item.required - Number(state.counts[item.id]) });
    } else if (status.kind === "overdue") {
      out.push({ item, kind: "interval" });
    }
  }
  return out;
}

function formComplete() {
  if (state.paramedic.trim().length < 2) return false;
  return state.items.every((item) => {
    if (item.type !== "qty") return true;
    const actual = Number(state.counts[item.id]);
    return state.counts[item.id] !== "" && state.counts[item.id] != null && Number.isInteger(actual) && actual >= 0;
  });
}

function emailLabel(email) {
  if (!email) return "—";
  if (email.reason === "sent") return t("sent");
  if (email.reason === "nothing_missing") return t("noShortMail");
  if (email.reason === "not_configured") return t("notConfigured");
  if (email.reason === "failed") return t("failed");
  return "—";
}

function render() {
  document.documentElement.lang = state.lang;
  document.documentElement.dir = state.lang === "ar" ? "rtl" : "ltr";
  document.title = t("appTitle");
  if (!state.me) {
    app.innerHTML = loginHtml();
    return;
  }
  const views = {
    check: checklistHtml,
    records: recordsHtml,
    items: itemsHtml,
    settings: settingsHtml,
  };
  const view = views[state.view] || checklistHtml;
  app.innerHTML = `${shellHtml()}${view()}`;
}

